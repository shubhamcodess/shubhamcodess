def gear(s: SVG, x: float, cy: float, px: float) -> float:
    """Pixel gear turning slowly; rows shade lime → cyan → violet. Returns width."""
    shades = ["lime"] * 4 + ["cyan"] * 4 + ["violet"] * 4
    s.css.append("@keyframes turn{to{transform:rotate(360deg)}}"
                 ".turn{transform-box:fill-box;transform-origin:center;animation:turn 9s linear infinite}")
    s.add('<g class="turn" shape-rendering="crispEdges">')
    _pixels(s, GEAR, x, cy - len(GEAR) * px / 2, px, lambda r: s.c(shades[r]))
    s.add("</g>")
    return len(GEAR[0]) * px


def terminal(s: SVG, x: float, y: float, w: float, h: float, right: str) -> None:
    """A dark terminal that types each command, cursor leading, then swaps to the next."""
    bg, cyc = s.c("shadow"), 3 * len(COMMANDS)
    s.rect(x, y, w, h, fill=bg, rx=6)
    cy = y + h / 2
    for i, c in enumerate(("#ff6ec7", "#fbbf24", "#bef264")):
        s.add(f'<circle cx="{x + 20 + i * 14}" cy="{cy}" r="4.5" fill="{c}"/>')
    px = x + 72
    s.text(px, cy + 4.5, "~/workbench", "m7", 13, "#5eead4")
    s.text(px + measure("~/workbench ", "m7", 13), cy + 4.5, "$", "m7", 13, "#bef264")
    cx = px + measure("~/workbench $ ", "m7", 13)
    s.text(x + w - 18, cy + 4, right, "m7", 10.5, "#9097a6", anchor="end", tracking=0.1)

    cw = measure("x", "m4", 13)
    span = 100 / len(COMMANDS)
    s.css.append(f"@keyframes vis{{0%,{span - 0.1:.1f}%{{opacity:1}}{span:.1f}%,100%{{opacity:0}}}}"
                 "@keyframes cur{50%{opacity:0}}.cur{animation:cur .9s steps(1) infinite}")
    s.defs.append(f'<clipPath id="term"><rect x="{cx - 2}" y="{y}" width="{x + w - 180 - cx}" height="{h}"/></clipPath>')
    s.add('<g clip-path="url(#term)">')
    for i, (cmd, note) in enumerate(COMMANDS):
        n = len(cmd) + 2 + len(note) + 1
        delay = (cyc - 3 * i) % cyc  # start offsets 0, -6s, -3s: each command gets its own third
        s.css.append(f"@keyframes type{i}{{0%{{transform:translateX(0)}}18%,100%{{transform:translateX({n * cw:.2f}px)}}}}"
                     f".g{i}{{animation:vis {cyc}s linear -{delay}s infinite}}"
                     f".t{i}{{animation:type{i} {cyc}s steps({n}) -{delay}s infinite}}")
        s.add(f'<g class="g{i}">')
        s.text(cx, cy + 4.5, cmd, "m4", 13, "#ebe7de")
        s.text(cx + (len(cmd) + 2) * cw, cy + 4.5, note, "m4", 13, "#9097a6")
        s.add(f'<g class="t{i}">')
        s.rect(cx + cw, cy - 8, n * cw + 40, 18, fill=bg, rx=0)
        s.rect(cx, cy - 8, cw, 17, fill="#bef264", rx=0, extra='class="cur"')
        s.add("</g></g>")
    s.add("</g>")


