NOTES = re.compile(r"<!-- NOTES:START -->.*?<!-- NOTES:END -->", re.S)


def hub_md(p: dict) -> str:
    path = WIKI / f"{page(p['title'])}.md"
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    kept = NOTES.search(old)
    notes = kept.group(0) if kept else "<!-- NOTES:START -->\n<!-- NOTES:END -->"
    rows = []
    for (_, doc, desc), ok in zip(DOCS, filed(p)):
        name = f"[**{doc}**]({quote(doc_page(p, doc))})" if ok else doc
        rows.append(f"| {name} | {desc} | {'Filed' if ok else 'Not yet'} |")
    return f"""{GENERATED}
{block(a(f"{GH}/{p['repo']}", pic(f"hub-{slug(p)}", f"{p['title']}: {p['dek']}")))}

| Doc | What it covers | Status |
|---|---|---|
{chr(10).join(rows)}

{notes}

[← Back to the Workbench](Home)
"""


def sidebar_md() -> str:
    lines = [GENERATED, block(a("Home", pic("sidebar", "The Workbench, project wiki"))), "",
             "**[Home](Home)**", "", "**The catalog**", ""]
    for p in PROJECTS:
        flags = filed(p)
        lines.append(f"- [{p['title']}]({quote(page(p['title']))}) <sub>{sum(flags)}/{len(DOCS)}</sub>")
        lines += [f"  - [{doc}]({quote(doc_page(p, doc))})" for (_, doc, _), ok in zip(DOCS, flags) if ok]
    lines += ["", "**Elsewhere**", "", f"- [GitHub profile ↗]({GH})", f"- [EverythingTech ↗]({SITE})",
              f"- [LinkedIn ↗]({LI})", ""]
    return "\n".join(lines)


def footer_md() -> str:
    return f"{GENERATED}\n{block(a(GH, pic('footer', 'Documented like it ships. Back to the profile.')))}\n"


