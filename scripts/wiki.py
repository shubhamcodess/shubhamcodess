def pic(name: str, alt: str, width: str = "100%") -> str:
    """One-line <picture> (GitHub splits multi-line ones). ?v= busts the image proxy's cache."""
    v = hashlib.sha1(b"".join((IMG / f"{name}-{t}.svg").read_bytes() for t in ("dark", "light"))).hexdigest()[:8]
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="{RAW}/{name}-dark.svg?v={v}">'
            f'<img alt="{alt}" src="{RAW}/{name}-light.svg?v={v}" width="{width}"></picture>')


def a(href: str, inner: str) -> str:
    return f'<a href="{href}">{inner}</a>'


def block(*items: str) -> str:
    return "<p>" + "\n".join(items) + "</p>"


