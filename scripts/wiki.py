def page(title: str) -> str:
    return title.replace(" ", "-")


def doc_page(p: dict, label: str) -> str:
    return f"{page(p['title'])}-—-{page(label)}"


def slug(p: dict) -> str:
    return page(p["title"]).lower()


def filed(p: dict) -> list[bool]:
    return [(WIKI / f"{doc_page(p, label)}.md").exists() for _, label, _ in DOCS]


def status(n: int) -> tuple[str, str]:
    if n == len(DOCS):
        return "FULLY DOCUMENTED", "lime"
    return (f"{n} OF {len(DOCS)} FILED", "amber") if n else ("DOCS PENDING", "pink")


